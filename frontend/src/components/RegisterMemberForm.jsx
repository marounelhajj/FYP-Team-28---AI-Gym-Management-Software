import { useEffect, useState } from "react";
import { createMember, fetchRegistrationQuote } from "../api/members.js";
import { BUTTON_COLORS } from "../styles/buttonColors.js";
import WaiverSection, { EMPTY_WAIVER, isWaiverComplete } from "./WaiverSection.jsx";

// User story: "As a receptionist, I want to register a new walk-in
// member's profile and membership plan, so that I can onboard new
// customers on the spot." Extended per: "As a receptionist, I want to
// process a new member's first payment during registration, so that
// their membership is activated immediately."
//
// A new member is always created as Active with today's join date - the
// receptionist supplies profile + plan info, plus the payment that
// justifies that activation. There's no amount field to type into: pricing
// comes straight from GET /api/plans/pricing (see fetchBranchPricing,
// already branch-promotion-aware) and is just shown once both plan and
// duration are picked - the backend computes the real price itself
// regardless of what's sent, so this is a genuine constraint, not just a
// disabled input.
//
// Extended per: "As a marketing staff member, I want to track sign-ups and
// redemptions generated by each individual campaign, so that I can measure
// ROI and reallocate budget accordingly." - a marketing offer code can be
// applied here too, same as a renewal (see RenewMembershipForm): the price
// preview (GET /api/members/registration-quote) is server-computed and
// already branch-promotion-aware, so there's nothing to duplicate
// client-side.
//
// The form ends with the member's waiver (SCRUM-83): the receptionist
// hands the device over so the member can read, tick and sign it, and the
// backend records the receptionist as the witness.
const EMPTY_FORM = {
  name: "", email: "", phone: "", branch: "", membershipPlan: "",
  paymentMethod: "", paymentDuration: "", referralCode: "",
  ...EMPTY_WAIVER,
};
const PAYMENT_METHODS = ["Cash", "Card", "Bank Transfer"];
const PAYMENT_DURATIONS = ["1 Month", "1 Year"];

export default function RegisterMemberForm({ filterOptions, onClose, onRegistered }) {
  const [form, setForm] = useState(EMPTY_FORM);
  const [fieldErrors, setFieldErrors] = useState({});
  const [submitError, setSubmitError] = useState(null);
  const [submitting, setSubmitting] = useState(false);
  const [quote, setQuote] = useState(null);
  const [quoteError, setQuoteError] = useState(null);
  const [quoteLoading, setQuoteLoading] = useState(false);
  const [quoteVersion, setQuoteVersion] = useState(0);
  // A marketing offer code the receptionist (or the new member) gives:
  // typed, then applied to the quote - same pattern as RenewMembershipForm.
  const [offerInput, setOfferInput] = useState("");
  const [offerCode, setOfferCode] = useState("");
  const [offerError, setOfferError] = useState(null);
  const waiverSigned = isWaiverComplete(form, form.name);

  // Server-computed price for the chosen plan/duration at the chosen branch
  // (factors in any running BranchPromotion, and the offer code if one's
  // applied) - the real price a payment would charge, not a client guess.
  useEffect(() => {
    setQuote(null);
    setQuoteError(null);
    if (!form.branch || !form.membershipPlan || !form.paymentDuration) return undefined;
    let cancelled = false;
    setQuoteLoading(true);
    fetchRegistrationQuote({
      branch: form.branch, membershipPlan: form.membershipPlan, duration: form.paymentDuration, offerCode,
    })
      .then((data) => {
        if (!cancelled) setQuote(data);
      })
      .catch((err) => {
        if (cancelled) return;
        if (err.fieldErrors?.offerCode) {
          // The code can't be used - say why, and price it without the code.
          setOfferError(err.fieldErrors.offerCode[0]);
          setOfferCode("");
        } else {
          setQuoteError(err.fieldErrors ? Object.values(err.fieldErrors).flat()[0] : err.message);
        }
      })
      .finally(() => {
        if (!cancelled) setQuoteLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [form.branch, form.membershipPlan, form.paymentDuration, offerCode, quoteVersion]);

  function applyOffer() {
    const code = offerInput.trim().toUpperCase();
    setOfferError(null);
    if (!code) return;
    setOfferCode(code);
    if (code === offerCode) setQuoteVersion((v) => v + 1);
  }

  function removeOffer() {
    setOfferCode("");
    setOfferInput("");
    setOfferError(null);
  }

  function update(field, value) {
    setForm((f) => ({ ...f, [field]: value }));
  }

  async function handleSubmit(e) {
    e.preventDefault();
    setSubmitting(true);
    setSubmitError(null);
    setFieldErrors({});

    try {
      const member = await createMember({ ...form, offerCode: quote?.offerCode || undefined });
      onRegistered(member);
    } catch (err) {
      if (err.fieldErrors?.offerCode) {
        // e.g. the last use of a capped offer went at another desk a moment ago.
        setOfferError(err.fieldErrors.offerCode[0]);
        setOfferCode("");
      } else if (err.fieldErrors) {
        setFieldErrors(err.fieldErrors);
      } else {
        setSubmitError(err.message);
      }
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div style={styles.overlay} onClick={onClose}>
      <div style={styles.modal} onClick={(e) => e.stopPropagation()}>
        <div style={styles.modalHeader}>
          <h2 style={styles.modalTitle}>Register New Member</h2>
          <button onClick={onClose} style={styles.closeButton} aria-label="Close">
            &times;
          </button>
        </div>

        <form onSubmit={handleSubmit}>
          <Field label="Full name" error={fieldErrors.name}>
            <input
              type="text"
              value={form.name}
              onChange={(e) => update("name", e.target.value)}
              style={styles.input}
              autoFocus
            />
          </Field>

          <Field label="Email" error={fieldErrors.email}>
            <input
              type="email"
              value={form.email}
              onChange={(e) => update("email", e.target.value)}
              style={styles.input}
            />
          </Field>

          <Field label="Phone" error={fieldErrors.phone}>
            <input
              type="tel"
              value={form.phone}
              onChange={(e) => update("phone", e.target.value)}
              style={styles.input}
            />
          </Field>

          <Field label="Branch" error={fieldErrors.branch}>
            <select
              value={form.branch}
              onChange={(e) => update("branch", e.target.value)}
              style={styles.input}
            >
              <option value="">Select a branch...</option>
              {filterOptions.branches.map((b) => (
                <option key={b} value={b}>
                  {b}
                </option>
              ))}
            </select>
          </Field>

          <Field label="Membership plan" error={fieldErrors.membershipPlan}>
            <select
              value={form.membershipPlan}
              onChange={(e) => update("membershipPlan", e.target.value)}
              style={styles.input}
            >
              <option value="">Select a plan...</option>
              {(filterOptions.plans || []).map((p) => (
                <option key={p} value={p}>
                  {p}
                </option>
              ))}
            </select>
          </Field>

          <Field label="Payment method" error={fieldErrors.paymentMethod}>
            <select
              value={form.paymentMethod}
              onChange={(e) => update("paymentMethod", e.target.value)}
              style={styles.input}
            >
              <option value="">Select a payment method...</option>
              {PAYMENT_METHODS.map((m) => (
                <option key={m} value={m}>
                  {m}
                </option>
              ))}
            </select>
          </Field>

          <Field label="Subscription duration" error={fieldErrors.paymentDuration}>
            <select
              value={form.paymentDuration}
              onChange={(e) => update("paymentDuration", e.target.value)}
              style={styles.input}
            >
              <option value="">Select a duration...</option>
              {PAYMENT_DURATIONS.map((d) => (
                <option key={d} value={d}>
                  {d}
                </option>
              ))}
            </select>
          </Field>

          <Field label="Offer code (optional)">
            <div style={styles.offerRow}>
              <input
                type="text"
                value={offerInput}
                onChange={(e) => {
                  setOfferInput(e.target.value.toUpperCase());
                  setOfferError(null);
                }}
                onKeyDown={(e) => {
                  if (e.key === "Enter") {
                    e.preventDefault();
                    applyOffer();
                  }
                }}
                placeholder="e.g. SUMMER20"
                style={{ ...styles.input, ...styles.offerInput }}
                aria-label="Offer code"
                maxLength={20}
              />
              {offerCode && quote?.offerCode === offerCode ? (
                <button type="button" onClick={removeOffer} style={styles.offerButton}>
                  Remove
                </button>
              ) : (
                <button type="button" onClick={applyOffer} style={styles.offerButton} disabled={!offerInput.trim()}>
                  Apply
                </button>
              )}
            </div>
            {offerError && <div style={styles.offerError}>{offerError}</div>}
            {!offerError && offerCode && quote && !quote.offerCode && quote.offerNote && (
              <div style={styles.hint}>{quote.offerNote}</div>
            )}
          </Field>

          <Field label="Referral code (optional)" error={fieldErrors.referralCode}>
            <input
              type="text"
              value={form.referralCode}
              onChange={(e) => update("referralCode", e.target.value.toUpperCase())}
              placeholder="e.g. 7F3KQ9"
              style={{ ...styles.input, ...styles.offerInput }}
              maxLength={12}
            />
            <div style={styles.hint}>If an existing member referred them, enter their code here.</div>
          </Field>

          {quoteLoading && <div style={styles.quoteLoading}>Calculating price...</div>}
          {quoteError && <div style={styles.errorBox}>{quoteError}</div>}

          {quote && (
            <Field label="Price">
              {quote.originalAmount && (
                <div style={styles.oldPriceRow}>
                  <span style={styles.oldPriceTag}>Old price</span>
                  <span style={styles.oldPriceAmount}>${quote.originalAmount}</span>
                </div>
              )}
              <div style={styles.priceDisplay}>${quote.amount}</div>
              {quote.promotion && <div style={styles.promo}>Includes the "{quote.promotion}" branch offer</div>}
              {quote.offerCode && (
                <div style={styles.promo}>
                  Offer {quote.offerCode}
                  {quote.offerName ? ` (${quote.offerName})` : ""}: -${quote.offerDiscount}
                </div>
              )}
              {quote.offerCode && quote.offerNote && <div style={styles.hint}>{quote.offerNote}</div>}
            </Field>
          )}

          <WaiverSection
            values={form}
            onChange={update}
            errors={fieldErrors}
            signerName={form.name}
            hint="Hand the device to the new member to read and sign."
          />

          {submitError && <div style={styles.errorBox}>{submitError}</div>}

          <div style={styles.actions}>
            <button type="button" onClick={onClose} style={styles.cancelButton}>
              Cancel
            </button>
            <button
              type="submit"
              disabled={submitting || !waiverSigned}
              title={waiverSigned ? undefined : "The member needs to sign the waiver first"}
              style={{ ...styles.submitButton, ...(waiverSigned ? null : styles.submitDisabled) }}
            >
              {submitting ? "Registering..." : "Register & charge payment"}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}

function Field({ label, error, children }) {
  const message = Array.isArray(error) ? error[0] : error;
  return (
    <div style={styles.field}>
      <label style={styles.label}>{label}</label>
      {children}
      {message && <div style={styles.fieldError}>{message}</div>}
    </div>
  );
}

